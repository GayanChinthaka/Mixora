package com.pokerlanka.mixora.lyrics

import android.content.Context
import com.pokerlanka.kugou.KuGou
import com.pokerlanka.mixora.constants.EnableKugouKey
import com.pokerlanka.mixora.utils.dataStore
import com.pokerlanka.mixora.utils.get

object KuGouLyricsProvider : LyricsProvider {
    override val name = "Kugou"
    override fun isEnabled(context: Context): Boolean =
        context.dataStore[EnableKugouKey] ?: true

    override suspend fun getLyrics(
        context: Context,
        id: String,
        title: String,
        artist: String,
        duration: Int,
        album: String?,
    ): Result<String> =
        KuGou.getLyrics(title, artist, duration, album)
}
